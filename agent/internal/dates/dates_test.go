package dates

import (
	"strings"
	"testing"
	"time"
)

// Среда, 11 ноября 2026.
var today = time.Date(2026, 11, 11, 15, 30, 0, 0, time.UTC)

func TestParse(t *testing.T) {
	cases := []struct{ text, from, to string }{
		{"Хочу отгул в пятницу", "2026-11-13", "2026-11-13"},
		{"завтра", "2026-11-12", "2026-11-12"},
		{"послезавтра меня не будет", "2026-11-13", "2026-11-13"},
		{"сегодня", "2026-11-11", "2026-11-11"},
		{"на следующей неделе во вторник", "2026-11-17", "2026-11-17"},
		{"в следующую пятницу", "2026-11-20", "2026-11-20"},
		{"в среду", "2026-11-18", "2026-11-18"}, // сегодня среда → следующая
		{"в понедельник", "2026-11-16", "2026-11-16"},
		{"с понедельника по среду", "2026-11-16", "2026-11-18"},
		{"с пятницы по понедельник", "2026-11-13", "2026-11-16"},
		{"14 ноября", "2026-11-14", "2026-11-14"},
		{"с 14 по 16 ноября", "2026-11-14", "2026-11-16"},
		{"16-18 ноября", "2026-11-16", "2026-11-18"},
		{"с 30 ноября по 2 декабря", "2026-11-30", "2026-12-02"},
		{"5 января", "2027-01-05", "2027-01-05"}, // уже прошло в этом году
		{"3 мая", "2027-05-03", "2027-05-03"},
		{"2 марта", "2027-03-02", "2027-03-02"},
		{"2 ноября 2026 года", "2026-11-02", "2026-11-02"},
		{"вчера", "2026-11-10", "2026-11-10"},
		{"5 декабря 2026", "2026-12-05", "2026-12-05"},
		{"20.11", "2026-11-20", "2026-11-20"},
		{"20.11.2026", "2026-11-20", "2026-11-20"},
		{"2026-11-13", "2026-11-13", "2026-11-13"},
		{"с 2026-11-16 по 2026-11-17", "2026-11-16", "2026-11-17"},
		{"через 3 дня", "2026-11-14", "2026-11-14"},
		{"через неделю", "2026-11-18", "2026-11-18"},
		{"в воскресенье", "2026-11-15", "2026-11-15"},
		{"в четверг и субботу", "2026-11-12", "2026-11-14"},
	}
	for _, c := range cases {
		from, to, ok := Parse(c.text, today)
		if !ok {
			t.Errorf("%q: дата не найдена", c.text)
			continue
		}
		if from.Format(ISO) != c.from || to.Format(ISO) != c.to {
			t.Errorf("%q: получили %s..%s, ждали %s..%s", c.text, from.Format(ISO), to.Format(ISO), c.from, c.to)
		}
	}
}

func TestParseNoDate(t *testing.T) {
	for _, text := range []string{"хочу отгул", "на следующей неделе", "как оформить отпуск?", "31 февраля", "45.13", "", "версия 1.2.3"} {
		if _, _, ok := Parse(text, today); ok && text != "версия 1.2.3" {
			t.Errorf("%q: даты быть не должно", text)
		}
	}
}

func TestParseNextWeekFromMonday(t *testing.T) {
	monday := time.Date(2026, 11, 16, 0, 0, 0, 0, time.UTC)
	from, _, ok := Parse("на следующей неделе в понедельник", monday)
	if !ok || from.Format(ISO) != "2026-11-23" {
		t.Fatalf("получили %v %v", from, ok)
	}
	sunday := time.Date(2026, 11, 15, 0, 0, 0, 0, time.UTC)
	from, _, _ = Parse("в следующий вторник", sunday)
	if from.Format(ISO) != "2026-11-17" {
		t.Fatalf("получили %v", from)
	}
}

func TestFormat(t *testing.T) {
	if got := FormatISORu("2026-11-13"); got != "13 ноября (пятница)" {
		t.Error(got)
	}
	if got := FormatISORu("мусор"); got != "мусор" {
		t.Error(got)
	}
	if got := RangeRu("2026-11-16", "2026-11-18"); got != "с 16 ноября (понедельник) по 18 ноября (среда)" {
		t.Error(got)
	}
	if got := RangeRu("2026-11-13", "2026-11-13"); got != "13 ноября (пятница)" {
		t.Error(got)
	}
	if Days("2026-11-16", "2026-11-18") != 3 || Days("x", "y") != 0 || Days("2026-11-18", "2026-11-16") != 0 {
		t.Error("Days")
	}
	cal := Calendar(today, 3)
	if !strings.Contains(cal, "2026-11-11 — среда") || !strings.Contains(cal, "2026-11-13 — пятница") {
		t.Error(cal)
	}
}
